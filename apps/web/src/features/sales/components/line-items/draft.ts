// Editable lines of a sales document (quote, invoice, POS cart, exchange). The editor works on
// this draft; prices come from the server (list price unless the user typed one) and the draft is
// turned into the API's SalesLineInput only when the document is saved.

export type SalesLineInput = components["schemas"]["SalesLineInput"];

export interface ItemDraft {
  kind: "item";
  /** React key, stable for the life of the line. */
  key: string;
  /** Id of the saved line, kept so the server can match it on save. */
  lineId?: string;
  skuId: string | null;
  /** Text shown in the product picker for the chosen SKU. */
  skuLabel: string;
  unitId: string | null;
  qty: Qty | null;
  /** A price the user typed for one unit; null keeps the server's list price. */
  price: Money | null;
  /** Line discount in percent (decimal string). */
  discountPct: string;
  savedDiscount?: SavedDiscount;
  color: ColorKey | null;
  /** Quy cách, free text (quotes). */
  spec: string;
}

export interface MixDraft {
  kind: "mix";
  key: string;
  lineId?: string;
  groupId: string;
  packs: Qty | null;
  discountPct: string;
  savedDiscount?: SavedDiscount;
  spec: string;
  /** Parts (dây, vỉ…) chosen per flavor SKU. */
  parts: Readonly<Record<string, Qty | null>>;
}

export type LineDraft = ItemDraft | MixDraft;

/**
 * The money discount of a saved line with the percent shown for it and the gross amount it was
 * taken from. The percent is rounded to two decimals, so recomputing money from it can drift by a
 * few dong (1.000đ on 30.000đ → 3,33% → 999đ); the saved amount is sent back while both still hold.
 */
export interface SavedDiscount {
  pct: string;
  gross: string;
  amount: Money;
}

/** The saved discount when neither its percent nor its gross amount changed, else null. */
export function keptDiscount(saved: SavedDiscount | undefined, pct: string, gross: DecimalLike): Money | null {
  return saved !== undefined && saved.pct === pct && dec(saved.gross).eq(dec(gross)) ? saved.amount : null;
}

let seq = 0;
const nextKey = () => `line-${++seq}`;

export function newItemLine(init: Partial<Omit<ItemDraft, "kind" | "key">> = {}): ItemDraft {
  return { kind: "item", key: nextKey(), skuId: null, skuLabel: "", unitId: null, qty: toQty(1), price: null, discountPct: "0", color: null, spec: "", ...init };
}

export function newMixLine(group: MixGroup): MixDraft {
  const parts: Record<string, Qty | null> = {};
  for (const item of group.items) if (item.active) parts[item.sku_id] = toQty(0);
  return { kind: "mix", key: nextKey(), groupId: group.id, packs: toQty(1), discountPct: "0", spec: "", parts };
}

/** Same line with the parts of another mix group (all zero). */
export function switchMixGroup(line: MixDraft, group: MixGroup): MixDraft {
  const fresh = newMixLine(group);
  return { ...line, groupId: group.id, parts: fresh.parts };
}

/** Percent of `discount` in `gross`, two decimals; 0 when there is no gross amount. */
function percentOf(discount: string, gross: string): string {
  const g = dec(gross);
  if (g.lte(0)) return "0";
  return toDecimalString(dec(discount).div(g).times(100).toDecimalPlaces(2));
}

/** The money discount a percent gives on qty × price, rounded to whole dong like the prototype. */
export function discountAmount(qty: string, price: string, pct: string): Money {
  return toDecimalString(roundHalfCeil(dec(qty).times(dec(price)).times(dec(pct)).div(100))) as Money;
}

/** True when the draft line was a manual price on the saved document. */
function isManual(source: unknown): boolean {
  return typeof source === "object" && source !== null && (source as { kind?: unknown }).kind === "manual";
}

/**
 * Saved lines → draft: item and combo lines one-to-one, a mix pack with its flavor children as one
 * mix line; gifts and combo components are generated by the server and not edited.
 */
export function linesToDraft(lines: readonly SalesLine[], colors: Pick<ColorMaps, "codeOf">, groups: readonly MixGroup[]): LineDraft[] {
  const out: LineDraft[] = [];
  const children = (parentId: string) => lines.filter((l) => l.parent_line_id === parentId && l.line_kind === "mix_flavor");
  for (const l of lines) {
    if (l.line_kind === "item" || l.line_kind === "combo") {
      if (l.sku_id === null) continue;
      const gross = toDecimalString(dec(l.qty).times(dec(l.unit_price)));
      const pct = percentOf(l.discount_amount, gross);
      out.push({
        kind: "item",
        key: nextKey(),
        lineId: l.id,
        skuId: l.sku_id,
        skuLabel: l.sku_code ? `${l.sku_code} · ${l.name}` : l.name,
        unitId: l.unit_id,
        qty: l.qty,
        price: isManual(l.price_source) ? l.unit_price : null,
        discountPct: pct,
        ...(dec(l.discount_amount).gt(0) ? { savedDiscount: { pct, gross, amount: l.discount_amount } } : {}),
        color: l.color_id === null ? null : colors.codeOf(l.color_id),
        spec: l.spec_text ?? "",
      });
    } else if (l.line_kind === "mix_pack" && l.mix_group_id !== null) {
      const group = groups.find((g) => g.id === l.mix_group_id);
      const flavors = children(l.id);
      const parts: Record<string, Qty | null> = {};
      for (const item of group?.items ?? []) if (item.active) parts[item.sku_id] = toQty(0);
      for (const f of flavors) {
        if (f.sku_id === null) continue;
        const perPart = group ? group.units_per_part : 1;
        parts[f.sku_id] = toQty(dec(f.base_qty).div(perPart));
      }
      const gross = sumDec(flavors.map((f) => dec(f.qty).times(dec(f.unit_price))));
      const discount = sumDec([l.discount_amount, ...flavors.map((f) => f.discount_amount)]);
      const pct = percentOf(toDecimalString(discount), toDecimalString(gross));
      out.push({
        kind: "mix",
        key: nextKey(),
        lineId: l.id,
        groupId: l.mix_group_id,
        packs: l.qty,
        discountPct: pct,
        ...(discount.gt(0) ? { savedDiscount: { pct, gross: toDecimalString(gross), amount: toDecimalString(discount) as Money } } : {}),
        spec: l.spec_text ?? "",
        parts,
      });
    }
  }
  return out;
}

const positive = (q: string | null): q is string => q !== null && dec(q).gt(0);

/** Parts chosen and room in the packs of a mix line, both in parts (dây). */
export function mixUsage(line: MixDraft, group: MixGroup): { cap: number; used: number } {
  const packs = line.packs === null ? 0 : Number(line.packs);
  const perPack = group.units_per_part > 0 ? group.units_per_pack / group.units_per_part : 0;
  const used = Object.values(line.parts).reduce<number>((acc, p) => acc + (p === null ? 0 : Number(p)), 0);
  return { cap: packs * perPack, used };
}

/** Units (base pieces) of a flavor in a mix line. */
export function flavorPieces(parts: string, group: MixGroup): Qty {
  return toQty(dec(parts).times(group.units_per_part));
}

/** A line the server can price: an item with SKU, unit and a positive quantity. */
export function isPriceable(line: LineDraft): line is ItemDraft & { skuId: string; unitId: string; qty: Qty } {
  return line.kind === "item" && line.skuId !== null && line.unitId !== null && positive(line.qty);
}

/** Reason the draft cannot be saved (prototype `draftToLines` messages), or null. */
export function draftProblem(lines: readonly LineDraft[], groups: readonly MixGroup[], unitName: (id: string) => string): string | null {
  let any = false;
  for (const l of lines) {
    if (l.kind === "item") {
      if (isPriceable(l)) any = true;
      continue;
    }
    const group = groups.find((g) => g.id === l.groupId);
    if (!group) return "Thùng mix: chọn nhóm mix vị.";
    // Parts are whole dây/vỉ: the server takes an integer and cannot read 1,5.
    const split = group.items.find((x) => {
      const p = l.parts[x.sku_id];
      return p !== null && p !== undefined && !dec(p).isInteger();
    });
    if (split) return `Thùng mix ${group.name}: số ${unitName(group.part_unit_id)} vị ${split.flavor_label} phải là số nguyên.`;
    const { cap, used } = mixUsage(l, group);
    if (!cap) return "Thùng mix: nhập số thùng.";
    if (!used) return "Thùng mix: chưa chọn vị nào.";
    if (used > cap) return `Thùng mix ${group.name}: đã chọn ${num(used)} ${unitName(group.part_unit_id)}, vượt ${num(l.packs ?? "0")} ${unitName(group.pack_unit_id)}.`;
    any = true;
  }
  return any ? null : "Thêm ít nhất một dòng hàng.";
}

export interface InputContext {
  idOf: ColorMaps["idOf"];
  /** Server list price per unit of a line (by key), used to turn the percent into money. */
  listPrice: (key: string) => Money | null;
  /** Server list price of one base piece of a mix flavor (by line key and SKU). */
  flavorPrice: (key: string, skuId: string) => Money | null;
  groups: readonly MixGroup[];
}

/**
 * Draft → SalesLineInput[]: empty item rows are dropped; a manual price is sent as unit_price;
 * the percent discount becomes money on the price in force; a mix line sends its packs and parts.
 */
export function draftToInput(lines: readonly LineDraft[], ctx: InputContext): SalesLineInput[] {
  const out: SalesLineInput[] = [];
  for (const l of lines) {
    if (l.kind === "item") {
      if (!isPriceable(l)) continue;
      const price = l.price ?? ctx.listPrice(l.key);
      const colorId = l.color === null ? null : ctx.idOf(l.color);
      const input: SalesLineInput = { sku_id: l.skuId, unit_id: l.unitId, qty: l.qty };
      if (l.lineId) input.id = l.lineId;
      if (colorId) input.color_id = colorId;
      if (l.price !== null) input.unit_price = l.price;
      if (price !== null && dec(l.discountPct).gt(0)) {
        input.discount_amount = keptDiscount(l.savedDiscount, l.discountPct, dec(l.qty).times(dec(price))) ?? discountAmount(l.qty, price, l.discountPct);
      }
      if (l.spec.trim()) input.spec_text = l.spec.trim();
      out.push(input);
      continue;
    }
    const group = ctx.groups.find((g) => g.id === l.groupId);
    if (!group || !positive(l.packs)) continue;
    const parts = Object.entries(l.parts).filter((e): e is [string, Qty] => positive(e[1]));
    const input: SalesLineInput = {
      mix_group_id: l.groupId,
      qty: l.packs,
      parts: parts.map(([skuId, p]) => ({ sku_id: skuId, parts: Number(p) })),
    };
    if (l.lineId) input.id = l.lineId;
    if (dec(l.discountPct).gt(0)) {
      const priced = parts.map(([skuId, p]) => ({ pieces: flavorPieces(p, group), price: ctx.flavorPrice(l.key, skuId) }));
      const gross = sumDec(priced.map((f) => (f.price === null ? "0" : dec(f.pieces).times(dec(f.price)))));
      const amounts = priced.map((f) => (f.price === null ? "0" : discountAmount(f.pieces, f.price, l.discountPct)));
      input.discount_amount = keptDiscount(l.savedDiscount, l.discountPct, gross) ?? (toDecimalString(sumDec(amounts)) as Money);
    }
    if (l.spec.trim()) input.spec_text = l.spec.trim();
    out.push(input);
  }
  return out;
}

export interface MergeResult {
  lines: LineDraft[];
  /** The line the picked one was merged into, for the "Đã gộp vào dòng …" toast. */
  mergedInto: ItemDraft | null;
}

/**
 * Picks a color on a line. When another line already has the same SKU, unit and color, the
 * quantities are added there and this line disappears (prototype `pickColor` / `posColor`).
 */
export function pickColor(lines: readonly LineDraft[], key: string, color: ColorKey): MergeResult {
  const line = lines.find((l): l is ItemDraft => l.kind === "item" && l.key === key);
  if (!line) return { lines: [...lines], mergedInto: null };
  const twin = lines.find((l): l is ItemDraft => l.kind === "item" && l.key !== key && l.skuId === line.skuId && l.unitId === line.unitId && l.color === color);
  if (!twin) return { lines: lines.map((l) => (l.key === key ? { ...line, color } : l)), mergedInto: null };
  const qty = toQty(dec(twin.qty ?? "0").plus(dec(line.qty ?? "0")));
  const merged: ItemDraft = { ...twin, qty };
  return { lines: lines.filter((l) => l.key !== key).map((l) => (l.key === twin.key ? merged : l)), mergedInto: merged };
}

/** Copy of a line for another color ("+ Thêm màu khác"), inserted right after it. */
export function splitColor(lines: readonly LineDraft[], key: string): LineDraft[] {
  const i = lines.findIndex((l) => l.key === key);
  const line = lines[i];
  if (!line || line.kind !== "item") return [...lines];
  const copy = newItemLine({ skuId: line.skuId, skuLabel: line.skuLabel, unitId: line.unitId, qty: toQty(1), discountPct: line.discountPct, spec: line.spec });
  return [...lines.slice(0, i + 1), copy, ...lines.slice(i + 1)];
}
